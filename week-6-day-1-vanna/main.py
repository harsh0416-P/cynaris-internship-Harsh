
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
from typing import Optional
from uuid import uuid4

from vanna import Agent
from vanna.core.registry import ToolRegistry
from vanna.core.user import User, UserResolver, RequestContext
from vanna.integrations.ollama import OllamaLlmService
from vanna.integrations.sqlite import SqliteRunner
from vanna.integrations.local.agent_memory import DemoAgentMemory
from vanna.tools import RunSqlTool


# 1. Local user authentication
class LocalUserResolver(UserResolver):
    async def resolve_user(self, request_context: RequestContext) -> User:
        return User(
            id="local-user",
            username="local-user",
            group_memberships=["user"]
        )


# 2. Ollama LLM
llm = OllamaLlmService(
    model="llama3.2:1b",
    host="http://localhost:11434",
    temperature=0.1
)


# 3. SQLite database connection
sql_runner = SqliteRunner(
    database_path="data/sales.db"
)


# 4. Register SQL tool
registry = ToolRegistry()

registry.register_local_tool(
    RunSqlTool(
        sql_runner=sql_runner,
        custom_tool_description=(
            "Execute SQL SELECT queries on the sales database. "
            "The sales table contains: sale_id, customer_name, "
            "product, category, amount, city, quantity. "
            "Use SQLite SQL syntax. Do not modify database records."
        )
    ),
    access_groups=["user"]
)


# 5. Agent memory
agent_memory = DemoAgentMemory(max_items=1000)


# 6. Create Vanna agent
agent = Agent(
    llm_service=llm,
    tool_registry=registry,
    user_resolver=LocalUserResolver(),
    agent_memory=agent_memory
)


# 7. FastAPI application
app = FastAPI(
    title="Cynaris SQL Analyst API",
    description="Natural Language to SQL using Vanna and Ollama",
    version="1.0.0"
)


class QueryRequest(BaseModel):
    question: str
    conversation_id: Optional[str] = None


@app.get("/")
async def home():
    return {
        "status": "running",
        "message": "Cynaris SQL Analyst API is ready"
    }


@app.post("/cia/sql-analyst")
async def sql_analyst(request: QueryRequest):

    if not request.question.strip():
        raise HTTPException(
            status_code=400,
            detail="Question cannot be empty"
        )

    conversation_id = request.conversation_id or str(uuid4())

    # Create Vanna request context
    request_context = RequestContext(metadata={})

    responses = []

    try:
        # Send question to Vanna agent
        async for component in agent.send_message(
            request_context,
            request.question,
            conversation_id=conversation_id
        ):
            simple_component = getattr(
                component, "simple_component", None
            )

            if simple_component:
                text = getattr(simple_component, "text", None)

                if text:
                    responses.append(text)

        return {
    "success": True,
    "conversation_id": conversation_id,
    "question": request.question,

    # Final response generated by the AI
    "ai_answer": responses[-1] if responses else None,

    # Actual output returned by the SQL execution tool
    "database_result": responses[0] if responses else None,

    "responses": responses
}
        

    except Exception as error:
        raise HTTPException(
            status_code=500,
            detail=str(error)
        )
